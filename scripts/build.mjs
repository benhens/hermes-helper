// Joins src/ into desktop/plugin.js: plain text in, plain JavaScript out, no tools or downloads.
// Hermes loads exactly one file per plugin, and that file may import only @hermes/plugin-sdk,
// react and react/jsx-runtime. So the build:
//   1. reads the src/ files in the order below,
//   2. drops the imports between our own files (./x.js) and merges the outside imports into one
//      line per package at the top,
//   3. removes `export` from everything except main.js's `export default`.
// Usage: node scripts/build.mjs          writes desktop/plugin.js
//        node scripts/build.mjs --check  fails if desktop/plugin.js is not the current build
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { talkProblems, slimTalkData } from './talk-data.mjs'
import { wantsProblems, slimWantsData } from './wants-data.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ORDER = ['model-name.js', 'model-status.js', 'model-call.js', 'talk-data.js', 'wants-data.js', 'key-check.js', 'secret-rule.js', 'setup-cards.js', 'steps-data.js', 'steps.js', 'state.js', 'kept.js', 'talk.js', 'settings-file.js', 'look.js', 'talk-css.js', 'layout.js', 'expressions.js', 'eyes.js', 'motion.js', 'reveal.js', 'character.js', 'setup-tab.js', 'bubble-link.js', 'quotes.js', 'talk-view.js', 'page.js', 'settings-page.js', 'main.js']
const ALLOWED = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime']
const OUT = path.join(ROOT, 'desktop', 'plugin.js')
// hhcontent's step text (a copy of the team's content/steps-v1.json) becomes src/steps-data.js, so
// the src files and the tests can import it like any other module. Plain data, no logic.
const STEPS_JSON = path.join(ROOT, 'content', 'steps-v1.json')
const STEPS_JS = path.join(ROOT, 'src', 'steps-data.js')

export function stepsDataSource() {
  const data = JSON.parse(fs.readFileSync(STEPS_JSON, 'utf8'))
  return [
    '// Generated by scripts/build.mjs from content/steps-v1.json (hhcontent\'s fixed step text). Edit the',
    '// JSON, then build; tests/steps.test.mjs checks the data (build-v1.md section 6).',
    `export const STEPS_DATA = ${JSON.stringify(data, null, 2)}`,
    ''
  ].join('\n')
}

// Helper's conversation window has the one style sheet of our own (src/talk.css). It becomes
// src/talk-css.js, a string the page puts into a <style> element inside our own page. Comments and
// line breaks are dropped; nothing else is changed.
const TALK_CSS = path.join(ROOT, 'src', 'talk.css')
const TALK_CSS_JS = path.join(ROOT, 'src', 'talk-css.js')

export function talkCssText(css = fs.readFileSync(TALK_CSS, 'utf8')) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map(line => line.trim())
    .filter(Boolean)
    .join('\n')
}

export function talkCssSource() {
  return [
    '// Generated by scripts/build.mjs from src/talk.css (the style sheet of Helper\'s conversation window).',
    '// Edit the CSS, then build; tests/talk-css.test.mjs checks it.',
    `export const TALK_CSS = ${JSON.stringify(talkCssText())}`,
    ''
  ].join('\n')
}

// hhcontent's talk data (a copy of the team's content/helper-talk-v2.json) becomes
// src/talk-data.js: checked first (scripts/talk-data.mjs; with any problem the build stops and no
// file is written), then cut down to the fields the code uses.
const TALK_JSON = path.join(ROOT, 'content', 'helper-talk-v2.json')
const SKILLS_JSON = path.join(ROOT, 'content', 'skills-list-v1.json')
const TALK_JS = path.join(ROOT, 'src', 'talk-data.js')

export function talkDataSource(json = JSON.parse(fs.readFileSync(TALK_JSON, 'utf8')), skills = JSON.parse(fs.readFileSync(SKILLS_JSON, 'utf8'))) {
  const problems = talkProblems(json)
  if (problems.length) throw new Error(`content/helper-talk-v2.json has ${problems.length} problem(s); the build stops and nothing is written:\n  ` + problems.join('\n  '))
  return [
    '// Generated by scripts/build.mjs from content/helper-talk-v2.json (hhcontent\'s talk data) and the',
    '// skill names of content/skills-list-v1.json: only the fields the code reads, and each line\'s source.',
    '// Edit the JSON, then build.',
    `export const TALK_DATA = ${JSON.stringify(slimTalkData(json, skills), null, 2)}`,
    ''
  ].join('\n')
}

// Every file the build writes into src/ before joining: [the file, its text, what it is made from].
// All texts are made before any is written, so a problem in one stops the build with nothing changed.
export function generatedSources() {
  return [
    [STEPS_JS, stepsDataSource(), 'content/steps-v1.json'],
    [TALK_CSS_JS, talkCssSource(), 'src/talk.css'],
    [TALK_JS, talkDataSource(), 'content/helper-talk-v2.json'],
    [WANTS_JS, wantsDataSource(), 'content/helper-wants-v1.json']
  ]
}

// hhcontent's wants data (a copy of the team's content/helper-wants-v1.json) becomes
// src/wants-data.js: checked first against the talk data, the skills list and the lines of the
// Hermes docs it quotes (scripts/wants-data.mjs; with any problem the build stops and nothing is
// written), then cut down to the fields the code uses.
const WANTS_JSON = path.join(ROOT, 'content', 'helper-wants-v1.json')
const DOCS_LINES_JSON = path.join(ROOT, 'content', 'docs-lines-v0.23.0.json')
const WANTS_JS = path.join(ROOT, 'src', 'wants-data.js')
const readJson = p => JSON.parse(fs.readFileSync(p, 'utf8'))

export function wantsDataSource(wants = readJson(WANTS_JSON), talk = readJson(TALK_JSON), skills = readJson(SKILLS_JSON), docs = readJson(DOCS_LINES_JSON)) {
  const problems = wantsProblems(wants, talk, skills, docs)
  if (problems.length) throw new Error(`content/helper-wants-v1.json has ${problems.length} problem(s); the build stops and nothing is written:\n  ` + problems.join('\n  '))
  return [
    '// Generated by scripts/build.mjs from content/helper-wants-v1.json (hhcontent\'s wants: the rows, the',
    '// groups, the skills of the two docs pages) and content/skills-list-v1.json (which skills are left',
    '// out), checked against content/docs-lines-v0.23.0.json. Only the fields the code reads. Edit the JSON, then build.',
    `export const WANTS_DATA = ${JSON.stringify(slimWantsData(wants, skills), null, 2)}`,
    ''
  ].join('\n')
}

export function buildSource() {
  const named = new Map(ALLOWED.map(s => [s, new Set()]))
  const bodies = []
  const onDisk = fs.readdirSync(path.join(ROOT, 'src')).filter(f => f.endsWith('.js')).sort()
  const missing = onDisk.filter(f => !ORDER.includes(f))
  if (missing.length) throw new Error(`src files not in the build order: ${missing.join(', ')}`)

  for (const file of ORDER) {
    const text = fs.readFileSync(path.join(ROOT, 'src', file), 'utf8')
    const out = []
    for (const line of text.split('\n')) {
      const imp = line.match(/^import\s+(.*?)\s+from\s+'([^']+)'\s*;?\s*$/)
      if (imp) {
        const [, what, spec] = imp
        if (spec.startsWith('./')) continue
        if (!ALLOWED.includes(spec)) throw new Error(`${file}: import from '${spec}' is not allowed in a Hermes plugin`)
        const names = what.match(/^\{([^}]*)\}$/)
        if (!names) throw new Error(`${file}: only named imports are supported: ${line}`)
        names[1].split(',').map(s => s.trim()).filter(Boolean).forEach(n => named.get(spec).add(n))
        continue
      }
      if (/^\s*import[\s{'"(]/.test(line)) throw new Error(`${file}: write each import on one line: ${line}`)
      if (/^export default\b/.test(line) && file !== 'main.js') throw new Error(`${file}: only main.js has a default export`)
      if (/^export\s*\{/.test(line)) throw new Error(`${file}: use export before the declaration instead: ${line}`)
      out.push(line.replace(/^export (?=(async )?function\b|const\b|let\b|class\b)/, ''))
    }
    bodies.push(`// ---- src/${file} ----\n` + out.join('\n').trim() + '\n')
  }

  const imports = ALLOWED.filter(s => named.get(s).size)
    .map(s => `import { ${[...named.get(s)].sort().join(', ')} } from '${s}'`)
    .join('\n')
  return [
    '// Helper: a Hermes Desktop plugin. Built by scripts/build.mjs from src/; edit src/, not this file.',
    '// Licence: MIT (see LICENSE).',
    imports,
    '',
    bodies.join('\n')
  ].join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [file, text, from] of generatedSources()) {
    const name = path.relative(ROOT, file)
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
    if (now === text) continue
    if (process.argv.includes('--check')) {
      console.error(`${name} is out of date with ${from}: run node scripts/build.mjs`)
      process.exit(1)
    }
    fs.writeFileSync(file, text)
    console.log(`wrote ${name} from ${from}`)
  }
  const next = buildSource()
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (now !== next) {
      console.error('desktop/plugin.js is out of date: run node scripts/build.mjs')
      process.exit(1)
    }
    console.log('desktop/plugin.js is up to date')
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true })
    fs.writeFileSync(OUT, next)
    console.log(`wrote desktop/plugin.js (${next.length} characters)`)
  }
}
