// loom-fixes (helper-loom-fixes-v1 point 4): hhcontent's list of the names the Hermes docs give things (a copy of
// content/hermes-names-v1.json, 55df44fe) becomes src/names-data.js: each name's fixed sentence, the docs' own
// sentence with file and line (plain, without markdown), its aliases and its offer. Checked here: every entry has
// them, its offer is one of the talk data's sets, and an entry marked outside has its own quote. The docs quotes were
// checked by hhcontent's names.py against the docs (0 refused); the plugin's docs lines file does not hold those
// pages, so the build does not check them again (said in the loom-fixes report).
const NAMES_JSON = path.join(ROOT, 'content', 'hermes-names-v1.json')
const NAMES_JS = path.join(ROOT, 'src', 'names-data.js')
export function namesProblems(names, talk) {
  const out = []
  const sets = (talk.offers && talk.offers.sets) || {}
  const text = v => typeof v === 'string' && v.trim().length > 0
  for (const e of names.names || []) {
    if (!text(e.id) || !text(e.say) || !text(e.quote_plain) || !text(e.file) || !Number.isInteger(e.line)) out.push(`${e.id}: say, quote_plain, file or line missing`)
    if (!Array.isArray(e.aliases) || !e.aliases.length || !e.aliases.every(text)) out.push(`${e.id}: no aliases`)
    if (!sets[e.offer]) out.push(`${e.id}: offer ${e.offer} is not an offer set`)
    if (e.outside && !(text(e.outside.quote_plain) && text(e.outside.file) && Number.isInteger(e.outside.line))) out.push(`${e.id}: outside without its quote`)
    if (/[<>]/.test(e.say)) out.push(`${e.id}: angle brackets in its sentence`)
  }
  if (!(names.names || []).length) out.push('no names')
  return out
}
export function namesDataSource(names = JSON.parse(fs.readFileSync(NAMES_JSON, 'utf8')), talk = JSON.parse(fs.readFileSync(TALK_JSON, 'utf8'))) {
  const problems = namesProblems(names, talk)
  if (problems.length) throw new Error(`content/hermes-names-v1.json has ${problems.length} problem(s); the build stops and nothing is written:\n  ` + problems.join('\n  '))
  const slim = names.names.map(e => ({ id: e.id, name: e.name, kind: e.kind, say: e.say, file: e.file, line: e.line, quote: e.quote_plain, ...(e.outside ? { outside: { file: e.outside.file, line: e.outside.line, quote: e.outside.quote_plain } } : {}), aliases: e.aliases, offer: e.offer }))
  return [
    '// Generated by scripts/build.mjs from content/hermes-names-v1.json (hhcontent\'s names from the Hermes docs). Only the',
    '// fields the code reads. Edit the JSON, then build.',
    `export const NAMES_DATA = ${JSON.stringify(slim, null, 2)}`,
    ''
  ].join('\n')
}

