// What the page keeps in ctx.storage on the person's computer (src/state.js; talk v1).
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { readState, STORED_KEYS, TAB_IDS } from '../src/state.js'
import { PARKED } from '../scripts/build.mjs'

const store = obj => (k, d) => (k in obj ? obj[k] : d)

// dash-v1: the tabs; the first build's step and answers are no longer read. loom-fixes: My setup is out (his words,
// Loom 3:22), so a stored 'my_setup' opens the Dashboard
test('first open: the Dashboard tab, Helper\'s window 460 px wide', () => {
  assert.deepEqual(TAB_IDS, ['dashboard', 'learn'])
  assert.deepEqual(readState(store({})), { tab: 'dashboard', helperWidth: 460 })
  assert.deepEqual(readState(store({ tab: 'my_setup' })), { tab: 'dashboard', helperWidth: 460 })
})

test('remembered values come back, the dragged width too', () => {
  for (const tab of TAB_IDS) assert.deepEqual(readState(store({ tab, helperWidth: 512 })), { tab, helperWidth: 512 })
})

test('junk in storage falls back to the defaults; a width outside 360 to 600 is brought inside; the first build\'s tabs open the Dashboard', () => {
  const s = readState(store({ tab: 'x', step: 99, answers: 'o_phone', helperWidth: 'wide' }))
  assert.deepEqual(s, { tab: 'dashboard', helperWidth: 460 })
  for (const tab of ['setup', 'yours']) assert.equal(readState(store({ tab })).tab, 'dashboard')
  assert.equal(readState(store({ helperWidth: 90 })).helperWidth, 360)
  assert.equal(readState(store({ helperWidth: 4000 })).helperWidth, 600)
  assert.equal(readState(store({ helperWidth: 400.6 })).helperWidth, 401)
})

test('what the old helper header stored (side, hidden or closed, chat log) is no longer read', () => {
  const s = readState(store({ side: 'left', helper: 'closed', chatlog: true }))
  assert.deepEqual(Object.keys(s).sort(), ['helperWidth', 'tab'])
})

test('every key the plugin stores is on the allowed list: about the person, only the one record of what Helper keeps', () => {
  // The allowed list: the page's own state, and
  // 'kept', the record of what Helper keeps by fixed rules (src/kept.js; talk v2 row 3), and 'met'
  // (changes-14: Helper has said hello; true or nothing; last-reset, Lead 11 Nov: removed by Forget all, a full reset).
  // (dash-v1: the Dashboard stores nothing; the step list's step and answers left with it)
  // loom-fixes (Lead's point 17): 'talk', the last 50 lines of the conversation (src/talk-keep.js), and 'helperHidden'
  assert.deepEqual([...STORED_KEYS].sort(), ['helperHidden', 'helperWidth', 'kept', 'met', 'tab', 'talk'])
  const dir = path.resolve(import.meta.dirname, '..', 'src')
  const found = new Set()
  let calls = 0
  // (dash-v1: the parked files are not in the built plugin, so not read here; the parked Your setup stored 'remember')
  for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.js') && !PARKED.includes(x))) {
    // normal-chat: the docs chunks' data line is the docs' own text (it mentions storage), not code
    const src = fs.readFileSync(path.join(dir, f), 'utf8').replace(/^export const DOCS_CHUNKS = .*$/m, '')
    for (const m of src.matchAll(/storage\s*\.\s*(\w+)\s*\(\s*([^,)]*)/g)) {
      calls++
      const arg = m[2].trim()
      // page.js's keep(key, setter) writes under the key it is given: its two callers are read below
      if (arg === 'key' || arg === 'k') continue
      const literal = arg.match(/^'([\w-]+)'$/)
      assert.ok(literal, `${f}: a storage call whose key is not a plain text: ${m[0]}`)
      // remove only for the record of what Helper keeps: deleting everything removes it whole (loom-fixes: and the
      // kept conversation, by Clear chat and Forget all, and the hidden mark, by Show Helper; last-reset: the met mark,
      // by Forget all)
      assert.ok(['get', 'set'].includes(m[1]) || (m[1] === 'remove' && ['kept', 'talk', 'helperHidden', 'met'].includes(literal[1])), `${f}: storage.${m[1]}(${literal[1]})`)
      found.add(literal[1])
    }
    for (const m of src.matchAll(/\bkeep\(\s*'([\w-]+)'/g)) found.add(m[1])
    // storage is reached in no other way (handed on whole, or under another name). A generated data file
    // (one `export const NAME = {...}` holding pure JSON, checked by parsing it) has no code, so the words in
    // its strings are data, not storage (changes-16's key word list for "phone" holds the word "storage").
    let code = src.split('\n').filter(line => !line.trim().startsWith('//')).join('\n')
    const data = src.startsWith('// Generated by scripts/build.mjs') && code.match(/^\s*export const \w+ = (\{[\s\S]*\})\s*$/)
    if (data) {
      JSON.parse(data[1])
      code = ''
    }
    assert.doesNotMatch(code, /\bstorage\b(?!\.(?:get|set|remove)\()/, `${f}: storage reached another way`)
    // and nothing is kept outside the plugin's own storage: no browser storage, no cookies
    assert.doesNotMatch(code, /localStorage|sessionStorage|indexedDB|document\s*\.\s*cookie|caches\s*\.\s*open|navigator\s*\.\s*storage/, `${f}: storage outside ctx.storage`)
  }
  assert.ok(calls >= 8, `${calls} storage calls read`)
  for (const key of found) assert.ok(STORED_KEYS.includes(key), `a stored key that is not on the allowed list: ${key}`)
  for (const key of STORED_KEYS) assert.ok(found.has(key), `on the list but never stored: ${key}`)
  // the same in the built file Hermes loads
  // (normal-chat: without the docs chunks' data line, the docs' own text: it names localStorage in a sample)
  const built = fs.readFileSync(path.resolve(import.meta.dirname, '..', 'desktop', 'plugin.js'), 'utf8').replace(/^const DOCS_CHUNKS = .*$/m, '')
  assert.doesNotMatch(built, /localStorage|sessionStorage|indexedDB|document\s*\.\s*cookie|caches\s*\.\s*open|navigator\s*\.\s*storage/)
})

test('the Dashboard keeps nothing about the person\'s bots between visits: src/dash.js and src/dash-rules.js never touch storage', () => {
  for (const f of ['dash.js', 'dash-rules.js']) {
    const src = fs.readFileSync(path.resolve(import.meta.dirname, '..', 'src', f), 'utf8')
    assert.doesNotMatch(src, /storage/, f)
  }
})
